'use strict';
const { escapeHtml, richText } = require('./day03_question_checks.js');

function coding(id, difficulty, category, title, given, task, code, expected, explanation) {
  const outputs = Object.keys(expected);
  const checkVars = outputs.map(name => {
    const value = expected[name];
    const type = Array.isArray(value) ? 'list' : typeof value === 'string' ? 'string'
      : typeof value === 'boolean' ? 'bool' : 'int';
    return { name, type, value, exact: true };
  });
  return {
    id, difficulty, category, title, given, outputs, starterCode: '',
    prompt: '<strong>[' + difficulty + '] ' + escapeHtml(title) + '</strong>'
      + '<p>Given:</p><pre><code>' + escapeHtml(given) + '</code></pre>'
      + '<p>' + richText(task) + '</p>',
    ref: given + '\n\n' + code + '\nprint(' + outputs.join(', ') + ')\n',
    validation: { mode: 'variable_check', freshResults: true, checkVars },
    explanation: richText(explanation)
  };
}

