function interview(id, topic, question, answer, code, output, error) {
  VERIFICATION.interviews[id] = { code, output, ...(error ? { error } : {}) };
  return {
    id, topic, question: richText(question),
    answer: '<p>' + richText(answer) + '</p><pre><code>' + escapeHtml(code)
      + '</code></pre><p>' + (error ? 'Raises: ' : 'Output: ') + '<code>'
      + escapeHtml(error || output.trimEnd()) + '</code></p>'
  };
}

