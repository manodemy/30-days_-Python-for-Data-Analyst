'use strict';

function escapeHtml(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// Tildes delimit authored inline code; escape content before adding markup.
function richText(text) {
  return text.split('~').map((part, i) => i % 2
    ? '<code>' + escapeHtml(part) + '</code>' : escapeHtml(part)).join('');
}

const VERIFICATION = { concepts: {}, interviews: {} };
function mcq(id, type, topic, prompt, options, answer, explanation, probe) {
  VERIFICATION.concepts[id] = probe;
  return { id, type, topic, prompt: richText(prompt), options, answer, explanation: richText(explanation) };
}

