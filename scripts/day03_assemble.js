/** Assemble Day 03 from its authored sources. No audio or other days are rewritten. */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const theory = require('./day03_theory.js');
const { PRACTICE, TEST } = require('./day03_questions.js');
const { CONCEPT_CHECKS, OPTIONAL_CONCEPT_CHECKS, INTERVIEW } = require('./day03_question_checks.js');
const ROOT = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(ROOT, name), 'utf8');
const esc = value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function questionSections() {
  const renderCheck = q => '<details class="course-review-item" id="day03Check' + q.id + '">' +
    '<summary>' + String(q.id).padStart(2, '0') + '. ' + esc(q.type) + ': ' + esc(q.topic) + '</summary>' +
    '<form class="course-check" data-check-id="' + q.id + '"><fieldset><legend>' + q.prompt + '</legend>' +
    q.options.map((option, i) => '<label class="course-check-option"><input type="radio" name="check-' + q.id +
      '" value="' + i + '" required><span>' + esc(option) + '</span></label>').join('\n') +
    '</fieldset><button type="submit" class="course-check-submit">Check answer</button>' +
    '<p class="course-feedback" role="status" aria-live="polite"></p></form></details>';
  const checks = CONCEPT_CHECKS.map(renderCheck).join('\n') +
    '<details class="course-review-item"><summary>Optional deeper checks: Unicode and text behavior</summary>' +
    OPTIONAL_CONCEPT_CHECKS.map(renderCheck).join('\n') + '</details>';
  const interviews = INTERVIEW.map(q => '<details class="course-review-item" id="day03Interview' + q.id + '">' +
    '<summary>' + String(q.id).padStart(2, '0') + '. ' + q.question + '</summary>' +
    '<div class="course-answer">' + q.answer + '</div></details>').join('\n');
  const solutions = TEST.map(q => '<details class="course-review-item" id="day03TestAnswer' + q.id + '">' +
    '<summary>Test ' + String(q.id).padStart(2, '0') + ': ' + esc(q.title || q.topic || 'Reference answer') + '</summary>' +
    '<div class="course-answer">' + q.prompt + '<pre class="course-code"><code>' + esc(q.ref) + '</code></pre>' +
    (q.explanation ? '<p>' + q.explanation + '</p>' : '') + '</div></details>').join('\n');
  const heading = (n, title) => '<h2 class="heading-box-wrap"><span class="heading-num-box">' + n +
    '</span><span class="heading-title-box">' + title + '</span></h2>';
  return '<div class="course-design-v1" data-course-design="1.0">' +
    '<section class="course-section" id="day03KnowledgeChecks">' + heading('09', 'Knowledge checks') +
    '<p class="course-lead">Concepts, output prediction, debugging and expression completion.</p>' + checks + '</section>' +
    '<section class="course-section" id="day03InterviewQuestions">' + heading('10', 'Interview questions') + interviews + '</section>' +
    '<section class="course-section" id="day03TestReferences">' + heading('11', 'Test review') +
    '<details class="course-review-item"><summary>Reference answers: ' + TEST.length + ' coding problems</summary>' +
    solutions + '</details></section></div>';
}

const content = {
  day: 3, title: 'Python Strings & Text Processing', emoji: '\u{1F524}',
  designVersion: '1.0',
  media: { mode: 'study', reason: 'Narration recording pending' },
  prerequisites: ['pyDay01', 'pyDay02'],
  sections: [...theory.SECTIONS, { id: 'day03KnowledgeChecks', title: 'Knowledge checks', number: 9 }, { id: 'day03InterviewQuestions', title: 'Interview questions', number: 10 }, { id: 'day03TestReferences', title: 'Test review', number: 11 }],
  slides: [{ title: 'Python Strings & Text Processing', html: theory.HTML + questionSections() }],
  practiceQuestions: PRACTICE.map(q => ({ ...q, starterCode: '' })),
  testQuestions: TEST.map(q => ({ ...q, starterCode: '' })),
  conceptChecks: [...CONCEPT_CHECKS, ...OPTIONAL_CONCEPT_CHECKS.map(q => ({ ...q, optional: true }))],
  interviewQuestions: INTERVIEW
};
if (PRACTICE.length !== 20 || TEST.length !== 25) throw new Error('Unexpected Day03 question coverage');
if (TEST.some(q => !q.ref || !q.validation)) throw new Error('Coding tests require executable answers and rubrics');
const bundle = '// Generated by scripts/day03_assemble.js. Edit the authored sources.\n' +
  'window.COURSE_CONTENT = window.COURSE_CONTENT || {};\n' +
  'window.COURSE_CONTENT.pyDay03 = ' + JSON.stringify(content, null, 2) + ';\n';
vm.runInNewContext(bundle, { window: {} });

// Preserve the existing Day03 shell instead of recloning another day.
let shell = read('public/python/day03.html');
// Draft narration scripts are not consumed by a study-only lesson.
shell = shell.replace(/^.*<script src="\/python\/content\/py-narrations\.js[^\n]*\r?\n/gm, '');
shell = shell.replace(/(<title>)[\s\S]*?(<\/title>)/, '$1Manodemy - Python Day 03: Strings &amp; Text Processing$2');
shell = shell.replace(/(<div class="test-title">)[\s\S]*?(<\/div>)/, '$1Day 03 - Strings Assessment$2');
if (!shell.includes('data-course-design-shell')) shell = shell.replace('<body', '<body data-course-design-shell="1"');
if (!shell.includes('/python/course-design.css')) shell = shell.replace('</head>', '  <link rel="stylesheet" href="/python/course-design.css?v=156.0">\n</head>');
if (!shell.includes('/python/course-study.js')) shell = shell.replace('</body>', '  <script src="/python/course-study.js?v=156.0"></script>\n</body>');
shell = shell.replace(/(py-day-03\.js|python-engine\.js|python-grading-engine\.js|course-study\.js|course-design\.css)\?v=[\d.]+/g, '$1?v=156.0');
for (const prefix of ['public/python', 'python']) {
  fs.mkdirSync(path.join(ROOT, prefix, 'content'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, prefix, 'content/py-day-03.js'), bundle, 'utf8');
  fs.writeFileSync(path.join(ROOT, prefix, 'day03.html'), shell, 'utf8');
}
console.log(JSON.stringify({ designVersion: content.designVersion, practice: PRACTICE.length, codingTests: TEST.length,
  knowledgeChecks: CONCEPT_CHECKS.length, interviews: INTERVIEW.length, media: content.media.mode }));
